test('记录餐食与训练，查看五种分析，离线刷新并备份恢复', async ({ page, context }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await page.clock.install({ time: new Date('2026-10-20T04:00:00.000Z') });
  await page.goto('./#/calendar');
  await expect(page.getByRole('heading', { name: '把进步，记在日常.' })).toBeVisible();
  await expect(page.getByRole('button', { name: /2026-10-20，/ })).toHaveAttribute('aria-pressed', 'true');
  await page.goto('./#/nutrition');
  await page.getByRole('button', { name: '记录餐食', exact: true }).click();
  await page.getByLabel('食物名称').fill('验收酸奶');
  await page.getByLabel('能量（千卡 / 100 克）').fill('120');
  await page.getByLabel('蛋白质（克 / 100 克）').fill('4');
  await page.getByLabel('碳水（克 / 100 克）').fill('16');
  await page.getByLabel('脂肪（克 / 100 克）').fill('4');
  await page.getByLabel('可选份量名称').fill('杯');
  await page.getByLabel('每份克重（克）').fill('150');
  await page.getByRole('button', { name: '保存食物', exact: true }).click();
  await page.getByLabel('验收酸奶数量').fill('2');
  await page.getByRole('button', { name: '保存餐食', exact: true }).click();
  await expect(page.locator('.metric').filter({ hasText: '已记录摄入' })).toContainText('360');
  await page.getByRole('button', { name: '确认全天已记全' }).click();
  await expect(page.getByRole('button', { name: '已记全 · 点击取消' })).toBeVisible();
  await page.goto('./#/training');
  await page.getByRole('button', { name: '开始训练', exact: true }).click();
  await page.getByRole('button', { name: '选择动作', exact: true }).click();
  await page.getByLabel('搜索动作').fill('杠铃卧推');
  await page.getByRole('button', { name: '加入', exact: true }).click();
  await page.getByLabel('第1组重量').fill('50');
  await page.getByLabel('第1组次数').fill('10');
  await page.getByRole('button', { name: '第1组标记完成' }).click();
  await page.getByRole('button', { name: '添加一组' }).click();
  await page.getByRole('button', { name: '第2组标记完成' }).click();
  await page.clock.runFor(1000);
  await expect(page.getByRole('status').filter({ hasText: '已保存在本地' })).toBeVisible();
  await expect(page.locator('.workout-status')).toContainText('1,000 kg');
  await page.getByRole('button', { name: '完成训练', exact: true }).click();
  await expect(page.locator('.workout-history-row')).toHaveCount(1);
  await page.goto('./#/analytics?period=month&anchor=2026-10-20');
  await expect(page.getByRole('heading', { name: '看见积累的力量.' })).toBeVisible();
  for (const period of ['日', '周', '月', '季度', '年度']) {
    await page.getByRole('button', { name: period, exact: true }).click();
    await expect(page.getByRole('heading', { name: '摄入与目标' })).toBeVisible();
    await expect(page.locator('.metric').filter({ hasText: '完成训练' })).toContainText('1');
  }
  await expect(page.getByRole('heading', { name: '这一年的坚持' })).toBeVisible();
  await page.goto('./#/settings');
  await expect(page.getByTestId('app-version')).toHaveText(`v${pkg.version}`);
  await page.getByRole('button', { name: '设置目标', exact: true }).click();
  await page.getByLabel('每日能量目标（千卡）').fill('1800');
  await page.getByRole('button', { name: '保存目标', exact: true }).click();
  await expect(page.locator('.goal-highlight')).toContainText('1,800');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出完整备份' }).click();
  const download = await downloadEvent; const filename = await download.path();
  expect(filename).toBeTruthy();
  const backup = JSON.parse(await readFile(filename!, 'utf8'));
  expect(backup.appVersion).toBe(pkg.version); expect(backup.entities.meals).toHaveLength(1); expect(backup.entities.workouts).toHaveLength(1);
  await page.getByRole('button', { name: '清空本机数据', exact: true }).click();
  await page.getByLabel('请输入“清空全部数据”').fill('清空全部数据');
  await page.getByRole('button', { name: '清空全部数据', exact: true }).click();
  await expect(page.locator('.goal-highlight')).toContainText('—');
  await page.locator('input[type=file]').setInputFiles(filename!);
  await expect(page.getByText('文件验证通过')).toBeVisible();
  await page.getByRole('button', { name: '确认替换并恢复' }).click();
  await expect(page.locator('.goal-highlight')).toContainText('1,800');
  await page.goto('./#/calendar?date=2026-10-20');
  await expect(page.getByRole('button', { name: /2026-10-20，1次完成训练，饮食完整，360千卡/ })).toBeVisible();
  await page.screenshot({ path: 'test-results/calendar-desktop.png', fullPage: true });
  await page.reload();
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await expect(page.locator('.storage-status')).toContainText('离线可用');
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: '把进步，记在日常.' })).toBeVisible();
  await page.goto('./#/analytics?period=year&anchor=2026-10-20');
  await expect(page.getByRole('heading', { name: '这一年的坚持' })).toBeVisible();
  await context.setOffline(false);
  expect(errors).toEqual([]);
});

test('手机布局、版本、非法日期和子路径资源', async ({ page, baseURL }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto('./#/calendar');
  await expect(page.locator('.mobile-nav')).toBeVisible();
  for (const route of ['calendar', 'training', 'nutrition', 'analytics', 'settings', 'exercises', 'foods']) {
    await page.goto(`./#/${route}`);
    await expect(page.locator('main h1')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  await page.goto('./#/settings'); await page.screenshot({ path: 'test-results/settings-mobile.png', fullPage: true });
  await page.reload(); await expect(page.getByTestId('app-version')).toHaveText(`v${pkg.version}`);
  await page.goto('./#/day/2026-02-31'); await expect(page.getByRole('heading', { name: '这个日期无效' })).toBeVisible();
  const manifest = await (await page.request.get(`${baseURL}manifest.webmanifest`)).json();
  expect(manifest.scope).toBe(new URL(baseURL!).pathname); expect(manifest.start_url).toBe(new URL(baseURL!).pathname);
});
