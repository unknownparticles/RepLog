import { expect, test } from '@playwright/test';

test('食谱搜索筛选、份量、取消不入账与指定日期餐次保存', async ({ page }) => {
  await page.goto('./#/nutrition?date=2026-10-18');
  await page.locator('main').getByRole('link', { name: '健身食谱', exact: true }).click();
  await expect(page.getByRole('heading', { name: '健身食谱', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '蛋白 ≥20克/份', exact: true }).click();
  await expect(page.locator('.recipe-card')).toHaveCount(5);
  await page.getByRole('button', { name: '15分钟内', exact: true }).click();
  await expect(page.locator('.recipe-card')).toHaveCount(3);
  await expect(page.getByRole('heading', { name: '清煮虾仁', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '蛋奶素可选', exact: true }).click();
  await expect(page.locator('.recipe-card')).toHaveCount(2);
  await page.getByLabel('搜索食谱或食材').fill('鸡胸肉');
  await expect(page.getByText('没有匹配的食谱', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '清除筛选', exact: true }).click();
  await page.getByLabel('搜索食谱或食材').fill('鸡胸肉');
  await expect(page.locator('.recipe-card')).toHaveCount(1);
  await page.getByRole('button', { name: '查看凉拌鸡丝', exact: true }).click();
  await expect(page.getByLabel('归属日期')).toHaveValue('2026-10-18');
  await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await page.getByRole('link', { name: '饮食记录', exact: true }).click();
  await expect(page.locator('.record-row')).toHaveCount(0);
  await page.locator('main').getByRole('link', { name: '健身食谱', exact: true }).click();
  await page.getByRole('button', { name: '查看凉拌鸡丝', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('食用份数').fill('0');
  await expect(dialog.getByRole('button', { name: '确认计入饮食' })).toBeDisabled();
  await dialog.getByLabel('食用份数').fill('0.5');
  await expect(dialog.locator('.recipe-totals')).toContainText('143.8');
  await expect(dialog.locator('.recipe-ingredients')).toContainText('100 克');
  await dialog.getByLabel('归属日期').fill('2026-10-19');
  await dialog.getByLabel('餐次').selectOption('晚餐');
  await dialog.getByRole('button', { name: '确认计入饮食' }).click();
  await expect(page).toHaveURL(/nutrition\?date=2026-10-19/);
  await expect(page.getByLabel('饮食日期')).toHaveValue('2026-10-19');
  const dinner = page.locator('.meal-section').filter({ has: page.getByRole('heading', { name: '晚餐', exact: true }) });
  await expect(dinner).toContainText('凉拌鸡丝 · 0.5 份');
  await dinner.getByRole('button', { name: '编辑晚餐', exact: true }).click();
  await expect(page.getByLabel('备注（可选）')).toHaveValue(/份\n营养/);
  await expect(page.getByLabel('备注（可选）')).toHaveValue(/HowToCook/);
  await page.getByLabel('鸡胸肉（生、去皮）（食谱估算）数量', { exact: true }).fill('110');
  await page.getByRole('button', { name: '保存餐食', exact: true }).click();
  await expect(dinner.locator('.record-body strong')).toHaveText('凉拌鸡丝 · 0.5 份');
  await expect(dinner).toContainText('110克');
  await page.reload(); await expect(dinner).toContainText('凉拌鸡丝 · 0.5 份');
});

test('手机布局、离线首次打开食谱、授权与入账', async ({ page, context, baseURL }) => {
  const external: string[] = [];
  page.on('request', request => { if (new URL(request.url()).origin !== new URL(baseURL!).origin) external.push(request.url()); });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto('./#/nutrition?date=2026-10-21');
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  // 从未进入食谱页，也应该已随应用预缓存。
  await context.setOffline(true);
  await page.locator('main').getByRole('link', { name: '健身食谱', exact: true }).click();
  await page.reload();
  await expect(page.locator('.recipe-card')).toHaveCount(8);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/recipes-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '查看燕麦鸡蛋饼', exact: true }).click();
  await page.getByLabel('食用份数').fill('1.5');
  await expect(page.locator('.recipe-ingredients')).toContainText('75 克');
  expect(await page.getByRole('dialog').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/recipe-details-mobile.png' });
  await page.getByRole('button', { name: '确认计入饮食', exact: true }).click();
  await expect(page.locator('.record-row')).toContainText('燕麦鸡蛋饼 · 1.5 份');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('./recipes/ATTRIBUTION.md'); await expect(page.locator('body')).toContainText('Unlicense');
  await page.goto('./recipes/LICENSE.txt'); await expect(page.locator('body')).toContainText('public domain');
  expect(external).toEqual([]);
  await context.setOffline(false);
});
